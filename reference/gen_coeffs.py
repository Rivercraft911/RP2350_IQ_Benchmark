"""Emit firmware/src/coeffs.h: integer RRC coefficients and expected table CRCs.

Run from the repo root:  python3 reference/gen_coeffs.py
"""
from __future__ import annotations

import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import iqlut as m  # noqa: E402

ALPHA = 0.20
HEADROOM_DB = 1.0
KAISER_BETA = 1.0     # window on the truncated RRC: L = 12 then passes the EN 302 307-1 mask (analyze.py)
VARIANTS = [(2, 8), (2, 10), (2, 12), (4, 8), (4, 10), (4, 12), (8, 8), (8, 10)]
OUT = Path(__file__).resolve().parents[1] / "firmware" / "src" / "coeffs.h"


def table_crc(lut: m.Lut) -> tuple[int, int]:
    return (zlib.crc32(lut.words(True).tobytes()), zlib.crc32(lut.words(False).tobytes()))


def main():
    lines = [
        "// Generated by reference/gen_coeffs.py. Do not edit.",
        f"// RRC alpha={ALPHA}, Kaiser beta={KAISER_BETA} window, {HEADROOM_DB} dB headroom below 14-bit"
        f" full scale, coefficients scaled by 2^{m.FRAC_BITS}.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define COEF_FRAC_BITS {m.FRAC_BITS}",
        "",
        "typedef struct {",
        "    uint8_t sps, L;",
        "    const int32_t *c;      // c[a*sps + p], a = symbol age",
        "    uint32_t crc_i, crc_q; // zlib CRC32 of the built I/Q table words",
        "} coef_set_t;",
        "",
    ]
    entries = []
    for sps, L in VARIANTS:
        lut = m.Lut(ALPHA, sps, L, KAISER_BETA, HEADROOM_DB)
        name = f"c_{sps}_{L}"
        vals = ", ".join(str(int(v)) for v in lut.coef)
        lines.append(f"static const int32_t {name}[{sps * L}] = {{{vals}}};")
        ci, cq = table_crc(lut)
        entries.append(f"    {{{sps}, {L}, {name}, 0x{ci:08x}u, 0x{cq:08x}u}},")
    lines += ["", "static const coef_set_t COEF_SETS[] = {", *entries, "};",
              f"#define N_COEF_SETS {len(VARIANTS)}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(OUT.parents[2])}")


if __name__ == "__main__":
    main()
