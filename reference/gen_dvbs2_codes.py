"""Emit firmware/src/dvbs2_codes.h (QPSK codes, EN 302 307-1) from reference/dvbs2/dvbs2_tables.py.

Also checks the BCH exponent lists typed into firmware/src/dvbs2.c against the reference tables,
which were transcribed independently (see reference/dvbs2/gen_tables.py).
Run from the repo root:  python3 reference/gen_dvbs2_codes.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "reference" / "dvbs2"))
import dvbs2_tables as T  # noqa: E402

RATES = ("1/4", "1/3", "2/5", "1/2", "3/5", "2/3", "3/4", "4/5", "5/6", "8/9", "9/10")
OUT = ROOT / "firmware" / "src" / "dvbs2_codes.h"


def check_bch_polys():
    src = (ROOT / "firmware" / "src" / "dvbs2.c").read_text()
    for name, key in (("G16", "normal"), ("G14", "short")):
        body = re.search(name + r"\[12\]\[\d+\] = \{(.*?)\};", src, re.S).group(1)
        rows = [tuple(int(v) for v in r.split(",")) for r in re.findall(r"\{([\d, ]+)\}", body)]
        assert rows == [tuple(p) for p in T.BCH_POLYS[key]], f"{name} differs from reference"


def main():
    check_bch_polys()
    lines = ["// Generated by reference/gen_dvbs2_codes.py from reference/dvbs2/dvbs2_tables.py.",
             "// QPSK codes of ETSI EN 302 307-1 V1.4.1, Tables 5a/5b, 7a/7b, 12, annexes B/C.",
             "#pragma once", '#include "dvbs2.h"', ""]
    entries = []
    for frame in ("normal", "short"):
        for mc, rate in enumerate(RATES, start=1):
            if (frame, rate) not in T.LDPC:
                continue
            kbch, kldpc, t = T.BCH_PARAMS[frame][rate]
            rows = T.LDPC[(frame, rate)]
            nldpc = 64800 if frame == "normal" else 16200
            assert kldpc % 360 == 0 and len(rows) == kldpc // 360
            tag = f"{frame[0]}{rate.replace('/', '_')}"
            flat = [x for r in rows for x in r]
            offs = [0]
            for r in rows:
                offs.append(offs[-1] + len(r))
            lines.append(f"static const uint16_t grp_{tag}[{len(offs)}] = {{{', '.join(map(str, offs))}}};")
            lines.append(f"static const uint16_t addr_{tag}[{len(flat)}] = {{{', '.join(map(str, flat))}}};")
            entries.append(f'    {{"{frame} {rate}", {nldpc}, {kldpc}, {kbch}, {T.Q[frame][rate]}, {mc}, '
                           f'{int(frame == "short")}, {t}, {len(rows)}, grp_{tag}, addr_{tag}}},')
    lines += ["", "static const dvbs2_code_t DVBS2_CODES[] = {", *entries, "};",
              f"#define N_DVBS2_CODES {len(entries)}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(entries)} codes; BCH polynomials match reference")


if __name__ == "__main__":
    main()
