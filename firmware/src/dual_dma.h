// Isolated digital bench engine: two PIO0 or four PIO2 SMs alternate the shared 16-bit bus.
// Descriptors or PIO RX FIFOs point to immutable axis-table rows. No RF qualification.
#pragma once
#include <stdbool.h>
#include <stdint.h>

enum {
    DUAL_DMA_ERR_TXSTALL_I = 1u << 0,
    DUAL_DMA_ERR_TXSTALL_Q = 1u << 1,
    DUAL_DMA_ERR_CAPTURE_STALL = 1u << 2,
    DUAL_DMA_ERR_CAPTURE_DMA = 1u << 3,
    DUAL_DMA_ERR_OUTPUT_DMA = 1u << 4,
    DUAL_DMA_ERR_POLL_GAP = 1u << 5,
    DUAL_DMA_ERR_CONFIG = 1u << 6,
    DUAL_DMA_ERR_STARTUP = 1u << 7,
};

typedef struct {
    uint64_t read_i, read_q;       // earliest not-issued chronological descriptor rows; safe reuse bound
    uint64_t issued_i, issued_q;   // exclusive high-water row bounds; use for ready/deadline checks
    uint32_t txstalls_i, txstalls_q;
    uint32_t errors;               // sticky DUAL_DMA_ERR_*; a fault stops all output SMs
    bool running;
} dual_dma_progress_t;

// Common output/capture faults only. No source-read, descriptor or physical-output cursor.
typedef struct {
    uint32_t txstalls_i, txstalls_q;
    uint32_t errors;
    bool running;
} dual_dma_faults_t;

// 5 <= count_log2 <= 13: each array has 2^count_log2 uint32_t entries and must be aligned
// to its byte size. DMA wrap is limited to 32 KiB. cpw=1..4 is clocks per output bus word.
// Fill both rings before start. Caller owns publication, reuse guards and ready deadlines.
// Poll faster than one ring period (leave >=8 rows for DMA/FIFO lookahead), otherwise
// wrapping read addresses cannot establish monotonic counts. Use an additional >=8-entry
// reuse guard because issued reads can be ahead of completed SRAM transactions.
bool dual_dma_start(const uint32_t *desc_i, const uint32_t *desc_q, unsigned count_log2,
                    unsigned cpw);
// Idle-only experimental schedule:0=all high/grouped IDs,1=control high/data low,
// 2=data high/control low,3=all high/adjacent control-data IDs. Default0.
bool dual_dma_set_schedule(unsigned mode);
unsigned dual_dma_get_schedule(void);
// Idle-only row format:2(default)=one symbol with IQ_FLAG baked into each I halfword;
// 4=two symbols, flag-free shared table, GPIO14 generated by optional side-set on OUT.
// 8=four symbols, flag-free shared table, with the same optional side-set flag.
// Each word holds two 16-bit slots. Both modes shift16 bits/OUT; paired mode maps only
// GPIO0..13 as data and holds GPIO15 low. Progress always counts descriptor rows.
bool dual_dma_set_row_words(unsigned row_words);
unsigned dual_dma_get_row_words(void);
// Idle-only writer count2(default,PIO0) or4(PIO2). Four writers require row_words4/8 and use
// even/odd descriptors from the same axis rings, each with its own FIFO and DMA DREQ.
// read_i/q report the first chronological row not yet issued, while issued_i/q include
// any ahead-of-order even/odd reads. Two-writer mode has identical read and issued bounds.
bool dual_dma_set_writers(unsigned writers);
unsigned dual_dma_get_writers(void);
// Idle-only BUS_PRIORITY register mask0..15: bits0/1/2/3 select the register fields
// PROC0/PROC1/DMA_R/DMA_W (hardware bits0/4/8/12). Default0. These are register labels;
// RP2350-E27 changes which ports they affect at FASTPERI/APB. Prior state is restored.
bool dual_dma_set_bus_priority(unsigned mask);
unsigned dual_dma_get_bus_priority(void);
// Fixed-point divider (units1/256):256,384,512,768,1024 =>1,1.5,2,3,4.
// Fractional output spacing and external HSTX/data phase are not DAC timing qualification.
bool dual_dma_start_div256(const uint32_t *desc_i, const uint32_t *desc_q,
                           unsigned count_log2, unsigned divider256);
// Experimental pin-free pointer source: selected row_words must be8 and writers2.
// Each source must be a distinct claimed PIO SM's RX FIFO with that SM's exact RX DREQ.
// Caller exclusively owns both pointer SMs and their input DMAs; this engine neither
// starts nor stops them. No other DMA/CPU consumer may drain those RX FIFOs/DREQs.
// Poll and honor the producer's own source/reuse deadlines; faults() supplies no cursor.
// Control DMA consumes one address only after its preceding8-word sample row completes;
// optional byte-swap converts the L8 pointer producer's RX format to numerical addresses.
// Prepare/start the producer with committed source data before calling this function.
// Output startup waits up to1ms for prefill, then retains the existing output/capture timing.
bool dual_dma_start_fifo(const volatile uint32_t *rx_i, const volatile uint32_t *rx_q,
                         unsigned dreq_i, unsigned dreq_q, bool control_bswap, unsigned cpw);
bool dual_dma_start_fifo_div256(const volatile uint32_t *rx_i, const volatile uint32_t *rx_q,
                                unsigned dreq_i, unsigned dreq_q, bool control_bswap,
                                unsigned divider256);
const char *dual_dma_last_error(void);
// Descriptor mode only. Calling this in FIFO mode sets CONFIG and stops output;
// use the pointer producer's separately defined source-read/reuse bounds instead.
dual_dma_progress_t dual_dma_progress(void);
// Both source modes: sticky output/capture errors halt all output SMs. Polling neither
// consumes pointer FIFOs nor derives cursors. The final snapshot is safe after stop.
dual_dma_faults_t dual_dma_faults(void);

// Samples 2*nwords 16-bit values then parks. The sampler takes 17 SM cycles/sample, normally
// a 17-bus-word stride. For output divider384 it instead uses divider256 (17 SYS cycles),
// requiring hardware-time reference indices floor((34*j+phase)/3)+offset, phase0..2.
// First sample is bits15:0. nwords1..8 uses only the joined RX FIFO and copies into buffer
// AFTER outputs stop; 9..4096 uses DMA during acquisition. No full-rate capture is used.
bool dual_dma_capture(uint32_t *buffer, uint32_t nwords);
bool dual_dma_capture_done(void);
uint32_t dual_dma_capture_count(void);            // completed 32-bit words; FIFO buffer valid after stop
uint32_t dual_dma_capture_errors(void);           // sticky capture-specific error bits
bool dual_dma_capture_fifo_only(void);            // effective mechanism; retained after stop

// Stops outputs/clock together, releases all claims and restores quiescent prior HW state.
// Final progress and capture counts remain readable after stop; no channel is read afterward.
void dual_dma_stop(void);
